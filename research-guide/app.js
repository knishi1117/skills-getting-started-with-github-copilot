  function isValidDate(value) {
    if (typeof value !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(value)) return false;
    const [y, m, d] = value.split("-").map(Number);
    const date = new Date(y, m - 1, d);
    return date.getFullYear() === y && date.getMonth() === m - 1 && date.getDate() === d;
  }

  function sanitizeLog(list) {
    const seen = new Set();
    const out = [];
    (Array.isArray(list) ? list : []).forEach((e) => {
      if (!e || !isValidDate(e.date) || !CARD_BY_ID[e.id]) return;
      const key = e.date + "|" + e.id;
      if (seen.has(key)) return;
      seen.add(key);
      out.push({ date: e.date, id: e.id });
    });
    return out;
  }

  function sanitizeTree(raw) {
    const tree = emptyTree();
    if (!raw || typeof raw !== "object") return tree;
    tree.lastWatered = isValidDate(raw.lastWatered) ? raw.lastWatered : null;
    tree.practiced = sanitizeLog(raw.practiced);
    tree.reviewed = sanitizeLog(raw.reviewed);
    return tree;
  }

  // 保存データを検証し、想定外の値は取り除く。形が壊れていれば null を返す。
  function sanitize(raw) {
    if (!raw || typeof raw !== "object" || !READABLE_VERSIONS.includes(raw.schemaVersion)) return null;
    const data = emptyData();
    if (Array.isArray(raw.favorites)) {
      data.favorites = raw.favorites.filter((id, i, arr) => CARD_BY_ID[id] && arr.indexOf(id) === i);
    }
    if (raw.practice && typeof raw.practice === "object") {
      Object.keys(raw.practice).forEach((id) => {
        const entry = raw.practice[id];
        if (!CARD_BY_ID[id] || !entry || entry.tried !== true) return;
        data.practice[id] = {
          tried: true,
          feedback: FEEDBACK_VALUES.includes(entry.feedback) ? entry.feedback : null,
        };
        // 日付のない以前の記録。日付は推測せず、お仕事の木には数えない
        if (entry.undated === true || raw.schemaVersion < 3) data.practice[id].undated = true;
      });
    }
    data.latestResult = sanitizeResult(raw.latestResult);
    data.progress = sanitizeProgress(raw.progress);
    const touched = Object.values(data.progress).map((p) => p.touched);
    data.seq = Math.max(Number.isInteger(raw.seq) && raw.seq > 0 ? raw.seq : 0, 0, ...touched);
    data.tree = sanitizeTree(raw.tree);
    return data;
  }

  // ガイドごとの進み具合：ステップ番号・選んだ状況・気になる点・確認リストの印だけを保存する
  function sanitizeProgress(raw) {
    const out = {};
    if (!raw || typeof raw !== "object") return out;
    Object.keys(raw).forEach((id) => {
      const guide = GUIDES[id];
      const p = raw[id];
      if (!guide || !CARD_BY_ID[id] || !p || typeof p !== "object") return;
      const sel = {};
      guide.groups.forEach((g) => {
        const v = p.sel && p.sel[g.id];
        if (g.choices.some(([c]) => c === v)) sel[g.id] = v;
      });
      out[id] = {
        step: Number.isInteger(p.step) && p.step >= 1 && p.step <= GUIDE_STEPS.length ? p.step : 1,
        sel,
        issue: guide.issues.some((i) => i.id === p.issue) ? p.issue : null,
        checks: Array.isArray(p.checks)
          ? p.checks.filter((n, i, a) => Number.isInteger(n) && n >= 0 && n < guide.final.length && a.indexOf(n) === i)
          : [],
        touched: Number.isInteger(p.touched) && p.touched > 0 ? p.touched : 0,
      };
    });
    return out;
  }

  function sanitizeResult(r) {
    if (!r || typeof r !== "object" || !Array.isArray(r.questionIds) || !r.answers) return null;
    if (r.questionIds.length !== AREAS.length) return null;
    const ok = AREAS.every((area, i) => {
      const q = QUESTION_BY_ID[r.questionIds[i]];
      return q && q.areaId === area.id && ANSWER_VALUES.includes(r.answers[area.id]);
    });
    if (!ok) return null;
    const answers = {};
    AREAS.forEach((a) => (answers[a.id] = r.answers[a.id]));
    const savedOn = typeof r.savedOn === "string" && /^\d{4}-\d{2}-\d{2}$/.test(r.savedOn) ? r.savedOn : null;
    return { questionIds: r.questionIds.slice(), answers, savedOn };
  }

